#!/usr/bin/env python3
"""Build web_preview/index.html: a single self-contained page (data + sim.js inlined).

    python tools/build_web_preview.py

Inputs: web_preview/app.html (template), web_preview/sim.js (JS port of game/core),
game/content/base (all JSON content). Re-run after changing any of them; CI checks that the
committed index.html is up to date.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BASE = REPO / "game" / "content" / "base"
WEB = REPO / "web_preview"


def load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def collect_content() -> dict:
    content: dict = {"routes": {}, "consists": {}, "vehicles": {}, "scenarios": {}}
    for route_json in sorted(BASE.glob("routes/*/route.json")):
        route = load(route_json)
        bundle = {"route": route}
        for key in ("track_graph", "geometry", "stations"):
            if key in route:
                bundle[key] = load(route_json.parent / route[key])
        content["routes"][route["id"]] = bundle
    for v in sorted(BASE.glob("rolling_stock/*/vehicles/*.json")):
        d = load(v)
        content["vehicles"][d["id"]] = d
    for c in sorted(BASE.glob("rolling_stock/*/consist.json")):
        d = load(c)
        content["consists"][d["id"]] = d
    for s in sorted(BASE.glob("scenarios/*.json")):
        d = load(s)
        content["scenarios"][d["id"]] = d
    return content


def stats() -> dict[str, str]:
    tests = 0
    for f in (REPO / "game" / "tests").rglob("test_*.gd"):
        tests += len(re.findall(r"^func test_", f.read_text(encoding="utf-8"), flags=re.M))
    parity = len(load(REPO / "game" / "tests" / "parity" / "parity_reference.json")["samples"])
    schemas = len(list((REPO / "schemas").glob("*.schema.json")))
    return {"__GODOT_TESTS__": str(tests), "__PARITY__": str(parity), "__SCHEMAS__": str(schemas)}


def build() -> str:
    page = (WEB / "app.html").read_text(encoding="utf-8")
    sim = (WEB / "sim.js").read_text(encoding="utf-8")
    data = json.dumps(collect_content(), ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    header = "<!-- GENERATED by tools/build_web_preview.py from web_preview/app.html — do not edit -->\n"
    page = page.replace("/*__SIM__*/", sim.replace("</script", "<\\/script")).replace("/*__DATA__*/", data)
    for key, value in stats().items():
        page = page.replace(key, value)
    return header + page


def main(argv: list[str]) -> int:
    out = WEB / "index.html"
    html = build()
    if "--check" in argv:
        if not out.exists() or out.read_text(encoding="utf-8") != html:
            print("web_preview/index.html is stale: run python tools/build_web_preview.py")
            return 1
        print("web_preview/index.html is up to date")
        return 0
    out.write_text(html, encoding="utf-8")
    print(f"wrote {out.relative_to(REPO)} ({len(html) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
